// Helper to filter incidents by provinceKey
export function getIncidentsByProvince(key: string): TerroristIncident[] {
  if (!key || key === 'all' || key === 'central') {
    return TERRORIST_INCIDENTS;
  }
  if (key === 'songkhla') {
    return TERRORIST_INCIDENTS.filter((i) => i.provinceKey === 'songkhla_risk' || i.provinceKey === 'songkhla');
  }
  return TERRORIST_INCIDENTS.filter((i) => i.provinceKey === key);
}
