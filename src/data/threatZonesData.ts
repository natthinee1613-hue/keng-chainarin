// Helper to check if a station is in the red risk list
export function getThreatInfo(stationName: string): SecurityThreatZoneInfo | undefined {
  return THREAT_ZONES_DATA.find((z) => stationName.includes(z.stationName) || z.stationName.includes(stationName));
}

export function isRedThreatZone(stationName: string): boolean {
  return !!getThreatInfo(stationName);
}
